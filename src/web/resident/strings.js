/** Keys that exist in one language but not in the other (an empty list means the two match). */
export function keyMismatches() {
  const en = Object.keys(strings.en);
  const fil = Object.keys(strings.fil);
  return {
    missingInFil: en.filter((k) => !(k in strings.fil)),
    missingInEn: fil.filter((k) => !(k in strings.en)),
  };
}

/** The text for a key in a language, with {words} filled in. An unknown key shows the key itself. */
export function translate(lang, key, vars = {}) {
  const table = strings[lang] ?? strings.en;
  const text = table[key] ?? strings.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : `{${name}}`));
}
